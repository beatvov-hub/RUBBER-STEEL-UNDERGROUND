import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createTestTarget } from './test-server.mjs';
await mkdir('artifacts', { recursive: true });
const target = await createTestTarget();
let browser;
try {
browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1060 } });
await page.addInitScript(() => { window.__rsuTrackPlays = []; const originalPlay = HTMLMediaElement.prototype.play; HTMLMediaElement.prototype.play = function () { window.__rsuTrackPlays.push(this.currentSrc || this.src); return originalPlay.call(this); }; });
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto(target.url);
assert.equal(await page.locator('#debug').count(),0);
assert.equal(await page.locator('#fullscreen-toggle').count(),1);
assert.equal(await page.locator('[data-stage]').count(),0);
await page.locator('#stage-select').click();assert.equal(await page.locator('[data-stage]').count(),50);
assert.equal(await page.locator('[data-stage="2"]').isDisabled(),true);
await page.locator('#home').click();await page.locator('#character-select').click();assert.equal(await page.locator('[data-character]').count(),4);
assert.equal(await page.locator('[data-character="fire"]').isDisabled(),true);
await page.locator('#home').click();await page.locator('#settings').click();
await page.locator('[data-setting="shake"]').fill('0');await page.locator('#home').click();
await page.locator('#start').click();
await page.waitForTimeout(800);assert.ok((await page.evaluate(()=>window.__rsuTrackPlays)).some(url=>/RSU-main.*\.mp3/.test(url)),'main BGM should start with a run');
assert.equal(await page.locator('#weapon-hint').textContent(), '精密単発');
assert.match(await page.locator('[data-weapon="triple"]').getAttribute('aria-label'), /外した3発も跳ね返る/);
await page.screenshot({ path: 'artifacts/gameplay.png', fullPage: true });
const rect = await page.locator('#game').boundingBox();
const pos = (x,y) => ({ x: rect.x + x/1120*rect.width, y: rect.y + y/640*rect.height });
// Fire one carefully aimed shot. Basic pursuer moves towards us on the same line.
const enemy = pos(800,170); await page.mouse.move(enemy.x, enemy.y); await page.mouse.down(); await page.waitForTimeout(60); await page.mouse.up();
await page.waitForTimeout(2200);
assert.equal(await page.locator('#enemies').textContent(), '00');
assert.equal(await page.locator('#exit').textContent(), 'OPEN');
// Miss a horizontal shot and stay in its return path to verify the actual UI death loop.
const aim = pos(850,520); await page.mouse.move(aim.x, aim.y); await page.mouse.down(); await page.waitForTimeout(60); await page.mouse.up();
await page.waitForTimeout(5700);
assert.ok(await page.locator('#retry').isVisible());
assert.match(await page.locator('#overlay').textContent(), /OWN BULLET/);
await page.screenshot({ path: 'artifacts/own-bullet-death.png', fullPage: true });
await page.locator('#retry').click(); await expect(page.locator('#rounds')).toHaveText('000 / 180');
await page.keyboard.press('Escape'); assert.ok(await page.locator('#resume').isVisible());
await page.locator('#resume').click();
await page.locator('[data-weapon="triple"]').click(); await page.waitForTimeout(100); assert.equal(await page.locator('#weapon').textContent(),'TRIPLE SHOT'); assert.equal(await page.locator('#weapon-hint').textContent(),'3方向 / 集団向け');
await page.keyboard.press('3'); await page.waitForTimeout(100); assert.equal(await page.locator('#weapon-hint').textContent(),'高威力 / 装甲・ボス');
await page.locator('#sound').click(); await page.reload(); assert.equal(await page.locator('#sound').textContent(),'SOUND OFF');
await page.setViewportSize({width:1000,height:800});await page.screenshot({path:'artifacts/title.png',fullPage:true});
await page.evaluate(()=>{const save=JSON.parse(localStorage.getItem('rsu-save'));save.reachedStage=50;save.completedStages=Array.from({length:49},(_,i)=>i+1);save.unlocked=['standard','fire','ice','thunder'];localStorage.setItem('rsu-save',JSON.stringify(save));});
await page.reload();await page.locator('#character-select').click();await page.locator('[data-character="thunder"]').click();
assert.ok((await page.locator('[data-character="thunder"]').getAttribute('class')).includes('selected'));
await page.locator('#home').click();await page.locator('#stage-select').click();await page.locator('[data-stage="50"]').click();
await page.waitForTimeout(800);assert.ok((await page.evaluate(()=>window.__rsuTrackPlays)).some(url=>/RSU-boss.*\.mp3/.test(url)),'boss BGM should start on stage 50');
assert.match(await page.locator('.facility-status').textContent(),/STAGE 50/);
await page.waitForTimeout(450);
assert.match(await page.locator('.top-left .overline').textContent(),/STAGE 50/);
await page.screenshot({path:'artifacts/stage-50.png',fullPage:true});
assert.deepEqual(errors, []);
console.log('Browser smoke PASS: title, 50-stage selection, character unlock, aimed kill, exit unlock, delayed own-bullet death, retry, pause, weapon switch, settings persistence.');
} finally {
  await browser?.close();
  await target.close();
}
